  (**
{%html:
<p>Training information
TrainingInfoProto stores information for training a model.
In particular, this defines two functionalities: an initialization-step
and a training-algorithm-step. Initialization resets the model
back to its original state as if no training has been performed.
Training algorithm improves the model based on input data.</p>
<p>The semantics of the initialization-step is that the initializers
in ModelProto.graph and in TrainingInfoProto.algorithm are first
initialized as specified by the initializers in the graph, and then
updated by the &quot;initialization_binding&quot; in every instance in
ModelProto.training_info.</p>
<p>The field &quot;algorithm&quot; defines a computation graph which represents a
training algorithm's step. After the execution of a
TrainingInfoProto.algorithm, the initializers specified by &quot;update_binding&quot;
may be immediately updated. If the targeted training algorithm contains
consecutive update steps (such as block coordinate descent methods),
the user needs to create a TrainingInfoProto for each step.</p>
%}
  *)
  and TrainingInfoProto : sig
    type t = {
      initialization:GraphProto.t option;
      (**
{%html:
<p>This field describes a graph to compute the initial tensors
upon starting the training process. Initialization graph has no input
and can have multiple outputs. Usually, trainable tensors in neural
networks are randomly initialized. To achieve that, for each tensor,
the user can put a random number operator such as RandomNormal or
RandomUniform in TrainingInfoProto.initialization.node and assign its
random output to the specific tensor using &quot;initialization_binding&quot;.
This graph can also set the initializers in &quot;algorithm&quot; in the same
TrainingInfoProto; a use case is resetting the number of training
iteration to zero.</p>
<p>By default, this field is an empty graph and its evaluation does not
produce any output. Thus, no initializer would be changed by default.</p>
%}
      *)

      algorithm:GraphProto.t option;
      (**
{%html:
<p>This field represents a training algorithm step. Given required inputs,
it computes outputs to update initializers in its own or inference graph's
initializer lists. In general, this field contains loss node, gradient node,
optimizer node, increment of iteration count.</p>
<p>An execution of the training algorithm step is performed by executing the
graph obtained by combining the inference graph (namely &quot;ModelProto.graph&quot;)
and the &quot;algorithm&quot; graph. That is, the actual
input/initializer/output/node/value_info/sparse_initializer list of
the training graph is the concatenation of
&quot;ModelProto.graph.input/initializer/output/node/value_info/sparse_initializer&quot;
and &quot;algorithm.input/initializer/output/node/value_info/sparse_initializer&quot;
in that order. This combined graph must satisfy the normal ONNX conditions.
Now, let's provide a visualization of graph combination for clarity.
Let the inference graph (i.e., &quot;ModelProto.graph&quot;) be</p>
<pre><code>tensor_a, tensor_b -&gt; MatMul -&gt; tensor_c -&gt; Sigmoid -&gt; tensor_d
</code></pre>
<p>and the &quot;algorithm&quot; graph be</p>
<pre><code>tensor_d -&gt; Add -&gt; tensor_e
</code></pre>
<p>The combination process results</p>
<pre><code>tensor_a, tensor_b -&gt; MatMul -&gt; tensor_c -&gt; Sigmoid -&gt; tensor_d -&gt; Add -&gt; tensor_e
</code></pre>
<p>Notice that an input of a node in the &quot;algorithm&quot; graph may reference the
output of a node in the inference graph (but not the other way round). Also, inference
node cannot reference inputs of &quot;algorithm&quot;. With these restrictions, inference graph
can always be run independently without training information.</p>
<p>By default, this field is an empty graph and its evaluation does not
produce any output. Evaluating the default training step never
update any initializers.</p>
%}
      *)

      initialization_binding:StringStringEntryProto.t list;
      (**
{%html:
<p>This field specifies the bindings from the outputs of &quot;initialization&quot; to
some initializers in &quot;ModelProto.graph.initializer&quot; and
the &quot;algorithm.initializer&quot; in the same TrainingInfoProto.
See &quot;update_binding&quot; below for details.</p>
<p>By default, this field is empty and no initializer would be changed
by the execution of &quot;initialization&quot;.</p>
%}
      *)

      update_binding:StringStringEntryProto.t list;
      (**
{%html:
<p>Gradient-based training is usually an iterative procedure. In one gradient
descent iteration, we apply</p>
<p>x = x - r * g</p>
<p>where &quot;x&quot; is the optimized tensor, &quot;r&quot; stands for learning rate, and &quot;g&quot; is
gradient of &quot;x&quot; with respect to a chosen loss. To avoid adding assignments
into the training graph, we split the update equation into</p>
<p>y = x - r * g
x = y</p>
<p>The user needs to save &quot;y = x - r * g&quot; into TrainingInfoProto.algorithm. To
tell that &quot;y&quot; should be assigned to &quot;x&quot;, the field &quot;update_binding&quot; may
contain a key-value pair of strings, &quot;x&quot; (key of StringStringEntryProto)
and &quot;y&quot; (value of StringStringEntryProto).
For a neural network with multiple trainable (mutable) tensors, there can
be multiple key-value pairs in &quot;update_binding&quot;.</p>
<p>The initializers appears as keys in &quot;update_binding&quot; are considered
mutable variables. This implies some behaviors
as described below.</p>
<pre><code>1. We have only unique keys in all &quot;update_binding&quot;s so that two
   variables may not have the same name. This ensures that one
   variable is assigned up to once.
2. The keys must appear in names of &quot;ModelProto.graph.initializer&quot; or
   &quot;TrainingInfoProto.algorithm.initializer&quot;.
3. The values must be output names of &quot;algorithm&quot; or &quot;ModelProto.graph.output&quot;.
4. Mutable variables are initialized to the value specified by the
   corresponding initializer, and then potentially updated by
   &quot;initializer_binding&quot;s and &quot;update_binding&quot;s in &quot;TrainingInfoProto&quot;s.
</code></pre>
<p>This field usually contains names of trainable tensors
(in ModelProto.graph), optimizer states such as momentums in advanced
stochastic gradient methods (in TrainingInfoProto.graph),
and number of training iterations (in TrainingInfoProto.graph).</p>
<p>By default, this field is empty and no initializer would be changed
by the execution of &quot;algorithm&quot;.</p>
%}
      *)

    }
    val make: ?initialization:GraphProto.t -> ?algorithm:GraphProto.t -> ?initialization_binding:StringStringEntryProto.t list -> ?update_binding:StringStringEntryProto.t list -> unit -> t
